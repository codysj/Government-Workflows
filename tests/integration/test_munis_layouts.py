"""Real Munis export layouts (GW-37), on synthetic data.

The fixtures in data/synthetic/tyler/munis_layouts/ re-shape the synthetic Tyler
data into layouts seen in public Munis output (headers verbatim; see that
folder's README and docs/tyler_assumptions.md section 0): Invoice Central's
Excel columns, the A/P Cash Disbursements Journal (apcshdsb), and the
Year-to-Date Budget Report (glytdbud) with its title block, totals, and footer.
"""
from __future__ import annotations

from datetime import date

import openpyxl
import pandas as pd
import pytest

from src.core import pipeline
from src.core.run_ledger import RunLedger
from src.ingest.csv_loader import read_csv_table, read_excel_table
from src.ingest.tyler import normalize_tyler_export
from src.workflows.registry import SYNTHETIC_DIR, get_descriptor

M = SYNTHETIC_DIR / "tyler" / "munis_layouts"


def _run(workflow_type, inputs, **kw):
    return pipeline.run_workflow(workflow_type, {k: str(v) for k, v in inputs.items()},
                                 ledger=RunLedger(":memory:"), provider=pipeline.MOCK, **kw)


def test_ap_review_on_munis_layouts_finds_what_the_canonical_sample_finds():
    canonical = _run("ap_duplicate_review", get_descriptor("ap_duplicate_review").sample_inputs())
    munis = _run("ap_duplicate_review", {
        "ap_invoices": M / "ap_invoice_central.csv",          # no vendor name, no payment columns
        "vendor_list": M / "vendor_list.csv",
        "check_register": M / "cash_disbursements_journal.csv",  # TYPE PRTD/VOID, footers
    })
    assert munis.preflight_status == "pass"
    assert sorted(f.rule_used for f in munis.findings) == sorted(f.rule_used for f in canonical.findings)
    assert munis.validation.passed
    # Names came from the vendor list; the payment date from the disbursements journal.
    assert any("Riverbend Electric" in f.description for f in munis.findings)
    assert any(f.rule_used == "payment_before_invoice_date" for f in munis.findings)


def test_budget_variance_on_a_munis_ytd_budget_report():
    report = M / "ytd_budget_report.csv"
    r = _run("budget_variance", {"budget": report, "actuals": report})
    assert r.preflight_status == "pass"
    assert r.summary["budget_amount_column"] == "revised_budget"
    assert r.summary["actual_amount_column"] == "ytd_expended"  # "YTD EXPENDED"
    assert r.summary["rows_without_account_keys_skipped"] == 8  # 4 totals x 2 sides
    # The 4 planted expense variances plus the revenue shortfall (credit sign).
    assert r.summary["flagged_variances"] == 5
    assert any("'object': '4010'" in f.description for f in r.findings)


def test_cash_disbursements_journal_normalizes():
    exp = normalize_tyler_export(M / "cash_disbursements_journal.csv", "check_register")
    df = exp.dataframe
    printed = df[df["vendor_number"] == "1022"]
    assert set(printed["vendor_name"]) == {"Valley Telecom Services"}  # "1022 Valley Telecom Services"
    assert set(df["status"]) >= {"PRTD", "VOID"}                        # TYPE -> status
    assert any("footer_total_rows" in w for w in exp.warnings)          # flagged, not fatal


