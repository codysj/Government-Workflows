def test_account_detail_history_layout(tmp_path):
    """glacthst columns: "YR/PR" (with * = unposted) and one signed AMOUNT."""
    p = tmp_path / "gl.csv"
    p.write_text(
        "Fund,Org,Object,YR/PR,JNL,EFF DATE,SRC,REF1,REF2,CHECK #,AMOUNT,Description\n"
        "100,1000,5210,2026/03,412,03/10/26,API,INV-1,ACME,50101,\"1,250.00\",Office supplies\n"
        "100,1000,4010,*26/03,413,03/11/26,CR,,,,-500.00,Fees\n"
        "** END OF REPORT - Generated by Finance User **,,,,,,,,,,,\n", encoding="utf-8")
    df = normalize_tyler_export(p, "gl_detail").dataframe
    assert list(df["fiscal_year"][:2]) == ["2026", "2026"] and list(df["period"][:2]) == ["03", "03"]
    assert list(df["unposted"][:2]) == [False, True]
    assert str(df["debit"][0]) == "1250.00" and df["credit"][0] is None
    assert df["debit"][1] is None and str(df["credit"][1]) == "500.00"
    assert df["check_number"][0] == "50101" and df["journal"][0] == "412"


@pytest.mark.parametrize("suffix", ["csv", "xlsx"])
def test_report_title_block_above_the_header_is_skipped(tmp_path, suffix):
    rows = [["CITY OF RIVERBEND", ""], ["YEAR-TO-DATE BUDGET REPORT", ""], ["", ""],
            ["Account", "Amount"], ["5010", "10.00"]]
    path = tmp_path / f"r.{suffix}"
    if suffix == "csv":
        path.write_text("\n".join(",".join(r).rstrip(",") for r in rows) + "\n", encoding="utf-8")
        df = read_csv_table(path)
    else:
        pd.DataFrame(rows).to_excel(path, header=False, index=False)
        df = read_excel_table(path)
    assert list(df.columns) == ["Account", "Amount"] and df.iloc[0].tolist() == ["5010", "10.00"]


def test_je_upload_workbook_cells_are_text(tmp_path):
    """Tyler's Standard Excel import needs Text cells: number-typed amounts can
    lose their decimals (190.00 read as 1.90) and dates must carry no time."""
    _run("je_upload_prep", get_descriptor("je_upload_prep").sample_inputs(), export_dir=tmp_path)
    book = openpyxl.load_workbook(next(tmp_path.rglob("je_upload.xlsx")))
    cells = [c for row in book.active.iter_rows(min_row=2) for c in row if c.value not in (None, "")]
    assert cells and all(c.data_type == "s" for c in cells)


