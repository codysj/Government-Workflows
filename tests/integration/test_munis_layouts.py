"""Real Munis export layouts (GW-37), on synthetic data.

The fixtures in data/synthetic/tyler/munis_layouts/ re-shape the synthetic Tyler
data into layouts seen in public Munis output (headers verbatim; see that
folder's README and docs/tyler_assumptions.md section 0): Invoice Central's
Excel columns, the A/P Cash Disbursements Journal (apcshdsb), and the
Year-to-Date Budget Report (glytdbud) with its title block, totals, and footer.
"""
